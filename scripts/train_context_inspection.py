"""Fit the bounded inspection-topic head. Run from the repository root."""
import csv
import json
import re
import unicodedata
from pathlib import Path

import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression

fixtures = Path("neural-core/fixtures")
output = Path("neural-core/src/main/java/com/omnidev/workspace/domain/neural/InspectionTopicHead.java")


def rows(path):
    with path.open(encoding="utf-8") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def tokens(text):
    text = unicodedata.normalize("NFKC", text).lower()
    text = re.sub("[ـً-ٰٟ]", "", text).translate(str.maketrans("أإآى", "اااي"))
    return re.findall(r"[^\W_]+", text)


samples = rows(fixtures / "context-inspection/examples.tsv")
train = [(row["text"], int(row["label"])) for row in samples if row["split"] == "train"]
train += [(r["text"], int(r["label"] in {"device", "repository", "build"}))
          for r in rows(fixtures / "text-intents.tsv") if r["split"] == "train"]
vector = CountVectorizer(analyzer=tokens, binary=True)
vector.fit([s for s, _ in train])
train += [(r["text"], 0) for r in rows(fixtures / "massive-refusal/corpus.tsv")
          if r["split"] == "train" and r["expected_domain"] in {"-", "chat"}]
model = LogisticRegression(C=5, solver="liblinear", class_weight="balanced", random_state=42)
model.fit(vector.transform([s for s, _ in train]), [v for _, v in train])
dev_negatives = [r["text"] for r in samples if r["split"] == "dev" and r["label"] == "0"]
cutoff = max(0.0, max(model.decision_function(vector.transform(dev_negatives))) + 0.25)
# The mobile head uses fixed point arithmetic. Fold bias and cutoff into one integer.
scale = 1000
bias = round((float(model.intercept_[0]) - cutoff) * scale)
weights = np.rint(model.coef_[0] * scale).astype(int)
items = sorted(zip(vector.get_feature_names_out(), weights))
def literals(values):
    return ",\n        ".join(", ".join(values[n:n + 8]) for n in range(0, len(values), 8))
output.write_text("""package com.omnidev.workspace.domain.neural;

// Generated by scripts/train_context_inspection.py.
public final class InspectionTopicHead {
    private InspectionTopicHead() {}
    public static final int BIAS = %d;
    private static final String[] TERMS = {
        %s
    };
    private static final int[] WEIGHTS = {
        %s
    };
    public static int weight(String token) {
        int index = java.util.Arrays.binarySearch(TERMS, token);
        return index < 0 ? 0 : WEIGHTS[index];
    }
}
""" % (bias, literals([json.dumps(t, ensure_ascii=False) for t, _ in items]),
       literals([str(v) for _, v in items])), encoding="utf-8")
print("train rows", len(train), "coefficients", len(items) + 1)
for split in ["dev", "test"]:
    batch = [r for r in samples if r["split"] == split]
    scores = vector.transform([r["text"] for r in batch]) @ weights + bias
    print(split, [(k, sum((s > 0) == (k == '1') for r, s in zip(batch, scores) if r['label'] == k),
                   sum(r['label'] == k for r in batch)) for k in ['1', '0']])
